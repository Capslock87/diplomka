window.currentLang = localStorage.getItem('lumina_lang') || 'ru';

function applyTranslations(lang) {
    if (!translations[lang]) return;
    window.currentLang = lang;
    localStorage.setItem('lumina_lang', lang);
    document.documentElement.lang = lang;

    // Update text content elements
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");
        if (translations[lang][key]) {
            el.textContent = translations[lang][key];
        }
    });

    // Update placeholders
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const key = el.getAttribute("data-i18n-placeholder");
        if (translations[lang][key]) {
            el.setAttribute('placeholder', translations[lang][key]);
        }
    });

    // Update values (e.g. input type="submit")
    document.querySelectorAll("[data-i18n-value]").forEach(el => {
        const key = el.getAttribute("data-i18n-value");
        if (translations[lang][key]) {
            el.value = translations[lang][key];
        }
    });

    // Update active button states
    document.querySelectorAll('.lang-btn').forEach(btn => {
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });

    // Dispatch a custom event so other scripts can re-render dynamic content
    document.dispatchEvent(new CustomEvent('languageChanged', { detail: lang }));
}

document.addEventListener('DOMContentLoaded', () => {
    applyTranslations(currentLang);

    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', (e) => {
            applyTranslations(e.target.getAttribute('data-lang'));
        });
    });
});
